// node build.mjs [--env preview|live] [--out dist]
// Plain static build, no packages: copies public/ to dist/, writes core/games.config.js and _headers from config/games.json (so the allowed addresses can never disagree),
// stamps version.json, and refuses to finish if the generated _headers breaks a rule (no '*', no inline script, no framing).
import { readFileSync, writeFileSync, mkdirSync, cpSync, rmSync, existsSync } from "node:fs";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

const ROOT = new URL("./", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");

export function gamesConfigJs(cfg, env) {
  const games = cfg.games.map((g) => ({ id: g.id, name: g.name, short: g.short, accent: g.accent, freeCap: g.freeCap, ready: g.ready, status: g.status, newScreens: g.newScreens, origin: g[env] }));
  return `// Generated by build.mjs from config/games.json (${env}). Do not edit.\nexport const ENV = ${JSON.stringify(env)};\nexport const CONSOLE_ORIGIN = ${JSON.stringify(cfg.consoleOrigin[env])};\nexport const GAMES = Object.freeze(${JSON.stringify(games, null, 1)});\n`;
}

/** the CSP: scripts and styles only from the console itself; the browser may talk only to the console and the six games; no framing of the console; the one allowed frame is a game's player-screen view */
export function headersFile(cfg, env) {
  const origins = cfg.games.map((g) => g[env]);
  const csp = [
    "default-src 'self'",
    "script-src 'self'",
    "style-src 'self'",
    "font-src 'self'",
    "img-src 'self' data:",
    `connect-src 'self' ${origins.join(" ")}`,
    `frame-src ${origins.map((o) => o + "/screenview/").join(" ")}`,
    "frame-ancestors 'none'",
    "base-uri 'none'",
    "form-action 'self'",
    "object-src 'none'",
  ].join("; ");
  const common = ["  X-Content-Type-Options: nosniff", "  Referrer-Policy: no-referrer", "  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=()", "  X-Frame-Options: DENY", `  Content-Security-Policy: ${csp}`];
  return [
    "/*", ...common, "",
    "/auth/*", "  Cache-Control: no-store", "",
    "/sw.js", "  Cache-Control: no-cache", "",
    "/gamesbar.js", "  Cache-Control: no-cache", "",
    "/gamesbar.css", "  Cache-Control: no-cache", "",
    "/core/*", "  Cache-Control: no-cache", "",
    "/screens/*", "  Cache-Control: no-cache", "",
    "/version.json", "  Cache-Control: no-store", "",
    "/sw-config.json", "  Cache-Control: no-store", "",
  ].join("\n");
}

/** returns a list of rule breaks in a _headers text (empty = fine) */
export function lintHeaders(text) {
  const bad = [];
  const m = /Content-Security-Policy:\s*(.+)/.exec(text);
  if (!m) return ["no Content-Security-Policy"];
  const dirs = Object.fromEntries(m[1].split(";").map((d) => d.trim()).filter(Boolean).map((d) => { const [k, ...v] = d.split(/\s+/); return [k, v]; }));
  for (const [k, v] of Object.entries(dirs)) {
    if (v.includes("*") || v.some((x) => /^https?:\/\/\*/.test(x) || x === "https:" || x === "http:")) bad.push(`${k} allows a wildcard`);
    if (v.some((x) => /unsafe-inline|unsafe-eval/.test(x)) && k === "script-src") bad.push("script-src allows inline or eval scripts");
  }
  if (!dirs["script-src"]) bad.push("no script-src");
  if (JSON.stringify(dirs["script-src"]) !== JSON.stringify(["'self'"])) bad.push("script-src must be exactly 'self'");
  if (!(dirs["frame-ancestors"] || []).includes("'none'")) bad.push("the console may be framed (frame-ancestors is not 'none')");
  if (!dirs["connect-src"]) bad.push("no connect-src");
  if ((dirs["default-src"] || []).join(" ") !== "'self'") bad.push("default-src must be 'self'");
  if (!/X-Frame-Options:\s*DENY/.test(text)) bad.push("no X-Frame-Options: DENY");
  return bad;
}

/** "29 Oct 2026, 16:15 IST" from an ISO time */
export const istText = (iso) => { const d = new Date(new Date(iso).getTime() + 19_800_000), m = ["Jan","Feb","Mar","Apr","May","Jun","Jul","Aug","Sep","Oct","Nov","Dec"][d.getUTCMonth()], p = (n) => String(n).padStart(2, "0"); return `${p(d.getUTCDate())} ${m} ${d.getUTCFullYear()}, ${p(d.getUTCHours())}:${p(d.getUTCMinutes())} IST`; };

export function build({ env = "preview", out = join(ROOT, "dist"), version = "0.0.0", commit = "dev", releasedAt = "" } = {}) {
  const cfg = JSON.parse(readFileSync(join(ROOT, "config/games.json"), "utf8"));
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });
  cpSync(join(ROOT, "public"), out, { recursive: true });
  writeFileSync(join(out, "core/games.config.js"), gamesConfigJs(cfg, env));
  const headers = headersFile(cfg, env);
  const problems = lintHeaders(headers);
  if (problems.length) throw new Error("the generated _headers breaks a rule: " + problems.join("; "));
  writeFileSync(join(out, "_headers"), headers);
  writeFileSync(join(out, "version.json"), JSON.stringify({ version, releasedAt, releasedAtIST: releasedAt ? istText(releasedAt) : "", commit, env, consoleVersion: version, builtAt: new Date().toISOString() }));
  return { out, headers };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const a = process.argv.slice(2), get = (n, d) => { const i = a.indexOf(n); return i >= 0 ? a[i + 1] : d; };
  const rel = existsSync(join(ROOT, "releases.json")) ? JSON.parse(readFileSync(join(ROOT, "releases.json"), "utf8"))[0] : undefined;
  const r = build({ env: get("--env", "preview"), out: resolve(get("--out", join(ROOT, "dist"))), version: rel?.version || "0.0.0", releasedAt: rel?.releasedAt || "" });
  console.log("built into " + r.out);
}
