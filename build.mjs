// node build.mjs [--env preview|live] [--out dist]
// Plain static build, no packages: copies public/ to dist/, writes core/games.config.js and _headers from config/games.json (so the allowed addresses can never disagree),
// stamps version.json, and refuses to finish if the generated _headers breaks a rule (no '*', no inline script, no framing).
import { readFileSync, writeFileSync, mkdirSync, cpSync, rmSync, existsSync } from "node:fs";
import { join, resolve } from "node:path";
import { execFileSync } from "node:child_process";
import { pathToFileURL } from "node:url";

const ROOT = new URL("./", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");

/** the vendored corporate-game-core manifests (pinned version), or null when none are vendored: then config/games.json alone is used */
export function readCore(root = ROOT) {
  const p = join(root, "vendor/game-core/manifests.json");
  return existsSync(p) ? JSON.parse(readFileSync(p, "utf8")) : null;
}
/** a core manifest in the shape the console screens read */
export function fromManifest(m) {
  const play = m.playModes.length > 1 ? ["auto", "manual"] : null; // auto-called / host-called: who calls the numbers
  const startModes = play ? m.startModes.flatMap((s) => play.map((p) => `${s}-start-${p}-play`)) : m.startModes.map((s) => `${s}-start`);
  return { labels: m.labels, caps: m.caps, startModes, rehearsalMax: m.rehearsalMax, prizeModes: m.prizeModes, organizerFinalSayPrizes: !!m.organizerFinalSay, goldenButton: m.goldenButton === "Claim" ? "claim" : "announce", pause: m.pauseSupport ? { by: ["organizer", "host"] } : undefined };
}
const same = (a, b) => JSON.stringify(a) === JSON.stringify(b);
/** where config/games.json and the vendored manifests disagree, in plain words ([] = they agree) */
export function conformance(cfg, core) {
  if (!core) return [];
  const bad = [];
  for (const g of cfg.games) {
    const m = core.manifests[g.manifestId || g.id];
    if (!m) { bad.push(`${g.id}: the core has no manifest "${g.manifestId || g.id}"`); continue; }
    const want = fromManifest(m);
    for (const k of Object.keys(want)) if (!same(want[k], g[k])) bad.push(`${g.id}: ${k} is ${JSON.stringify(g[k])} here but ${JSON.stringify(want[k])} in core ${core.version}`);
  }
  return bad;
}
/** the games with every manifest field taken from the core; a game the core does not know keeps its own file values */
export function withCore(cfg, core) {
  if (!core) return cfg;
  return { ...cfg, roles: core.roles || cfg.roles || [], games: cfg.games.map((g) => { const m = core.manifests[g.manifestId || g.id]; return m ? { ...g, ...fromManifest(m) } : g; }) };
}

export function gamesConfigJs(cfg, env, core = null) {
  cfg = withCore(cfg, core);
  const games = cfg.games.map((g) => ({ id: g.id, name: g.name, accent: g.accent, freeCap: g.freeCap, ready: g.ready, status: g.status, approvals: g.approvals || [], caps: g.caps || {}, startModes: g.startModes || [], rehearsalMax: g.rehearsalMax, pause: g.pause, prizeModes: g.prizeModes || [], organizerFinalSayPrizes: !!g.organizerFinalSayPrizes, goldenButton: g.goldenButton, roles: cfg.roles || [], features: g.features || [], origin: g[env] }));
  return `// Generated by build.mjs from config/games.json (${env}). Do not edit.\nexport const ENV = ${JSON.stringify(env)};\nexport const CONSOLE_ORIGIN = ${JSON.stringify(cfg.consoleOrigin[env])};\nexport const CORE = ${JSON.stringify(core ? { version: core.version, commit: core.commit } : null)};\nexport const GAMES = Object.freeze(${JSON.stringify(games, null, 1)});\n`;
}

/** the CSP: scripts and styles only from the console itself; the browser may talk only to the console and the six games; no framing of the console; the one allowed frame is a game's player-screen view */
export function headersFile(cfg, env) {
  const origins = cfg.games.map((g) => g[env]);
  const csp = [
    "default-src 'self'",
    "script-src 'self'",
    "style-src 'self'",
    "font-src 'self'",
    "img-src 'self' data:",
    `connect-src 'self' ${origins.join(" ")}`,
    `frame-src ${origins.map((o) => o + "/screenview/").join(" ")}`,
    "frame-ancestors 'none'",
    "base-uri 'none'",
    "form-action 'self'",
    "object-src 'none'",
  ].join("; ");
  const common = ["  X-Content-Type-Options: nosniff", "  Referrer-Policy: no-referrer", "  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=()", "  X-Frame-Options: DENY", `  Content-Security-Policy: ${csp}`];
  return [
    "/*", ...common, "",
    "/auth/*", "  Cache-Control: no-store", "",
    "/sw.js", "  Cache-Control: no-cache", "",
    "/gamesbar.js", "  Cache-Control: no-cache", "",
    "/gamesbar.css", "  Cache-Control: no-cache", "",
    "/core/*", "  Cache-Control: no-cache", "",
    "/screens/*", "  Cache-Control: no-cache", "",
    "/version.json", "  Cache-Control: no-store", "",
    "/sw-config.json", "  Cache-Control: no-store", "",
  ].join("\n");
}

/** returns a list of rule breaks in a _headers text (empty = fine) */
export function lintHeaders(text) {
  const bad = [];
  const m = /Content-Security-Policy:\s*(.+)/.exec(text);
  if (!m) return ["no Content-Security-Policy"];
  const dirs = Object.fromEntries(m[1].split(";").map((d) => d.trim()).filter(Boolean).map((d) => { const [k, ...v] = d.split(/\s+/); return [k, v]; }));
  for (const [k, v] of Object.entries(dirs)) {
    if (v.includes("*") || v.some((x) => /^https?:\/\/\*/.test(x) || x === "https:" || x === "http:")) bad.push(`${k} allows a wildcard`);
    if (v.some((x) => /unsafe-inline|unsafe-eval/.test(x)) && k === "script-src") bad.push("script-src allows inline or eval scripts");
  }
  if (!dirs["script-src"]) bad.push("no script-src");
  if (JSON.stringify(dirs["script-src"]) !== JSON.stringify(["'self'"])) bad.push("script-src must be exactly 'self'");
  if (!(dirs["frame-ancestors"] || []).includes("'none'")) bad.push("the console may be framed (frame-ancestors is not 'none')");
  if (!dirs["connect-src"]) bad.push("no connect-src");
  if ((dirs["default-src"] || []).join(" ") !== "'self'") bad.push("default-src must be 'self'");
  if (!/X-Frame-Options:\s*DENY/.test(text)) bad.push("no X-Frame-Options: DENY");
  return bad;
}

/** "29 Oct 2026, 16:15 IST" from an ISO time */
export const istText = (iso) => { const d = new Date(new Date(iso).getTime() + 19_800_000), m = ["Jan","Feb","Mar","Apr","May","Jun","Jul","Aug","Sep","Oct","Nov","Dec"][d.getUTCMonth()], p = (n) => String(n).padStart(2, "0"); return `${p(d.getUTCDate())} ${m} ${d.getUTCFullYear()}, ${p(d.getUTCHours())}:${p(d.getUTCMinutes())} IST`; };

export function build({ env = "preview", out = join(ROOT, "dist"), version = "0.0.0", commit = "dev", releasedAt = "" } = {}) {
  if (env === "live" && (!commit || commit === "dev")) throw new Error("a live build must carry the real git commit, not a placeholder");
  const cfg = JSON.parse(readFileSync(join(ROOT, "config/games.json"), "utf8"));
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });
  cpSync(join(ROOT, "public"), out, { recursive: true });
  const core = readCore();
  const off = conformance(cfg, core);
  if (off.length) throw new Error("config/games.json and the vendored game-core manifests disagree: " + off.join("; "));
  writeFileSync(join(out, "core/games.config.js"), gamesConfigJs(cfg, env, core));
  const headers = headersFile(cfg, env);
  const problems = lintHeaders(headers);
  if (problems.length) throw new Error("the generated _headers breaks a rule: " + problems.join("; "));
  writeFileSync(join(out, "_headers"), headers);
  writeFileSync(join(out, "version.json"), JSON.stringify({ version, releasedAt, releasedAtIST: releasedAt ? istText(releasedAt) : "", commit, env, consoleVersion: version, builtAt: new Date().toISOString() }));
  return { out, headers };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const a = process.argv.slice(2), get = (n, d) => { const i = a.indexOf(n); return i >= 0 ? a[i + 1] : d; };
  const rel = existsSync(join(ROOT, "releases.json")) ? JSON.parse(readFileSync(join(ROOT, "releases.json"), "utf8"))[0] : undefined;
  let commit = "";
  try { commit = execFileSync("git", ["rev-parse", "--short=12", "HEAD"], { cwd: ROOT, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim(); } catch { /* handled below */ }
  if (!/^[0-9a-f]{7,40}$/.test(commit) && get("--env", "preview") !== "test") { console.error("The git commit could not be read, so the build would carry no real commit. Run it inside the git folder."); process.exit(1); }
  const r = build({ env: get("--env", "preview"), out: resolve(get("--out", join(ROOT, "dist"))), version: rel?.version || "0.0.0", commit: commit || "dev", releasedAt: rel?.releasedAt || "" });
  console.log("built into " + r.out);
}
